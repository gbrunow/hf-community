/**
 * Everything an event says, in one place: the wording, the order of the blocks in a
 * description, where each link goes, and how titles are put together. Edit the text and the
 * layouts here; the code only fills in the placeholders.
 *
 * Templates contain {placeholders}, filled in when an event is made. An unknown placeholder
 * is an error (it would otherwise reach the calendar as literal braces), so run
 * `npm run verify` after editing.
 *
 * Links. Every link placeholder ending in "Url" also exists with "Short" added
 * ({rowUrl} and {rowUrlShort}), which is the link passed through shortenUrl below. A short
 * link is only made if a template uses it.
 *
 * Emojis and label colors are not here: they are the styles in config.js (EVENT_STYLES).
 */
const CONTENT = {
  // ---- Wording ---------------------------------------------------------------------------

  contact: 'Community calendar by Gui Brunow (gbrunow@outlook.com).',

  // The landing page, which has every way to subscribe and counts the visits. {shareUrl} is the
  // calendar's raw public feed, which opens a subscribe prompt on Apple devices.
  share: 'Share this calendar:\nhttps://gbrunow.github.io/hf-community/',

  disclaimer: 'DISCLAIMER: Not an official Higher Fire calendar.',

  // Only the script's events say this; a hand-made event never does. It is also how the
  // script's events are told from hand-made ones, so don't leave it out of any layout
  // that describes an event.
  aiNotice:
    'Events are generated by AI from the kiln notes and may contain mistakes; times are ' +
    'approximate.',

  // Closes an event's description. {check}: the sentence in `sources` below.
  notice: '{aiNotice} {check}',

  // Closes a calendar's own description. {sheetUrl}: the spreadsheet.
  calendarNotice:
    '{aiNotice} Check the kiln notes before relying on an event:\n{sheetUrl}',

  // Between blocks. The most that fit on one line in Apple Calendar's event details on iPhone.
  rule: '─'.repeat(19),

  // ---- Where an event came from -----------------------------------------------------------
  // `source` is the block that says what the event was made from, and links to it; `check`
  // tells people where to confirm it.
  //   kiln:     {dateLabel} "Fri, Oct 9"; {text} the note; {rowUrl} the note's row in the sheet
  //   discard:  {tabName}; {tabUrl} the schedule's tab
  //   classes:  {dateLabel}; {rowUrl}
  //   closures: {dateLabel}; {rows} the original text, one quoted line per row; {rowUrl}
  sources: {
    kiln: {
      source: 'Original note ({dateLabel}):\n\n"{text}"\n{rowUrl}',
      check: 'Check the original note before relying on an event.',
    },
    discard: {
      source: 'Original schedule ({tabName}):\n{tabUrl}',
      check: 'Check the original schedule before relying on an event.',
    },
    classes: {
      source: 'Original row ({dateLabel}):\n{rowUrl}',
      check: 'Check the original row before relying on an event.',
    },
    closures: {
      source: 'Original ({dateLabel}):\n{rows}\n{rowUrl}',
      check: 'Check the original text before relying on an event.',
    },
  },

  // ---- The space an event takes -----------------------------------------------------------
  // The heading, then a line for each thing the sheet says; {value} is the cell as written.
  space: {
    heading: 'Space taken:',
    wheels: 'Wheels: {value}',
    people: 'People: {value}',
    handBuilding: 'Hand-building: {value}',
    handBuildingArea: 'Hand-building area',
    glazing: 'Class will be glazing.',
  },

  // ---- Titles -----------------------------------------------------------------------------
  // {count}: the number of people, when the sheet gives one. {emoji}: from EVENT_STYLES.
  titleWithCount: '{title} · {count}',
  titleWithEmoji: '{emoji} {title}',

  // ---- Layout -----------------------------------------------------------------------------
  // The blocks of a description, top to bottom, with a blank line between them. A block that
  // has nothing to say (no space, no existing text) drops out, and so does any rule left
  // at the top, at the bottom or doubled up.
  //   Blocks: space, source, contact, share, disclaimer, notice, calendarNotice, existing, rule
  layouts: {
    // An event the script makes.
    event: ['space', 'rule', 'source', 'rule', 'contact', 'share', 'rule', 'disclaimer', 'notice'],
    // An event made by hand, which gets what's below its own text ({existing}) appended once.
    handMade: ['existing', 'rule', 'contact', 'share', 'rule', 'disclaimer'],
    // The calendar itself.
    calendar: ['contact', 'share', 'rule', 'disclaimer', 'calendarNotice'],
  },

  // ---- Links ------------------------------------------------------------------------------
  // Turns a long link into a short one, for the {...UrlShort} placeholders. It runs when an
  // event is made, so it should be quick and shouldn't fail; as it stands it changes nothing,
  // so a template using {rowUrlShort} shows the full link.
  /** @param {string} url */
  shortenUrl: (url) => url,
};

/**
 * Fills a template's placeholders. Anything that isn't a key of `values` is an error.
 *
 * @param {string} template
 * @param {Record<string, string>} values
 * @returns {string}
 */
function render_(template, values) {
  return template.replace(/\{(\w+)\}/g, (_match, name) => {
    if (name in values) return values[name];
    const base = name.endsWith('Short') ? name.slice(0, -'Short'.length) : null;
    if (base && base in values) return CONTENT.shortenUrl(values[base]);
    throw new Error(`Unknown placeholder {${name}} in "${template.slice(0, 40)}"`);
  });
}

/**
 * The blocks every layout draws from, filled in from the values.
 *
 * @param {Record<string, string>} values
 * @returns {Record<string, string>}
 */
function blocks_(values) {
  /** @type {Record<string, string>} */
  const all = { aiNotice: CONTENT.aiNotice, ...values };
  return {
    contact: render_(CONTENT.contact, all),
    share: render_(CONTENT.share, all),
    disclaimer: render_(CONTENT.disclaimer, all),
    notice: all.check ? render_(CONTENT.notice, all) : '',
    calendarNotice: all.sheetUrl ? render_(CONTENT.calendarNotice, all) : '',
    rule: CONTENT.rule,
    space: values.space ?? '',
    source: values.source ?? '',
    existing: values.existing ?? '',
  };
}

/**
 * Lays blocks out in the order a layout gives, dropping empty ones and the rules that would
 * then lead, trail or double up.
 *
 * @param {'event' | 'handMade' | 'calendar'} layout
 * @param {Record<string, string>} blocks
 * @returns {string}
 */
function compose_(layout, blocks) {
  /** @type {(string | null)[]} null stands for a rule */
  const parts = [];
  for (const name of CONTENT.layouts[layout]) {
    if (!(name in blocks)) throw new Error(`Unknown block "${name}" in the ${layout} layout`);
    if (name === 'rule') {
      if (parts.length && parts[parts.length - 1] !== null) parts.push(null);
    } else if (blocks[name]) {
      parts.push(blocks[name]);
    }
  }
  while (parts.length && parts[parts.length - 1] === null) parts.pop();
  return parts.map((part) => part ?? CONTENT.rule).join('\n\n');
}
