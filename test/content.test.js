const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createWorld } = require('./harness');
const { eventsTabs } = require('./fixture');

const newWorld = () => createWorld({ tabs: eventsTabs() });
const calendarOf = (world) => world.context.CalendarApp.createCalendar('A test calendar');

// Sample values for each kind of source, with the placeholders its template documents.
const SAMPLES = {
  kiln: { dateLabel: 'Fri, Oct 9', text: 'Bisque loaded', rowUrl: 'https://sheet.test/row' },
  discard: { tabName: 'Discard Schedule', tabUrl: 'https://sheet.test/tab' },
  classes: { dateLabel: 'Fri, Oct 9', rowUrl: 'https://sheet.test/row' },
  closures: { dateLabel: 'Fri, Oct 9', rows: '"CLOSED"', rowUrl: 'https://sheet.test/row' },
};

test('every kind of source renders with its documented placeholders and no braces left over', () => {
  const world = newWorld();
  const calendar = calendarOf(world);
  for (const [kind, values] of Object.entries(SAMPLES)) {
    for (const space of ['', world.fn.spaceLabel_('10', 'all of HB').detail]) {
      const text = world.fn.eventDescription_(calendar, kind, values, space);
      assert.doesNotMatch(text, /[{}]/, `${kind}: ${text}`);
      assert.ok(text.includes('https://sheet.test/'), `${kind} links its source`);
    }
  }
});

test('a description never starts or ends with a rule, or has two in a row', () => {
  const world = newWorld();
  const calendar = calendarOf(world);
  const rule = world.eval('CONTENT.rule');
  const check = (text, what) => {
    const sections = text.split('\n\n');
    assert.notEqual(sections[0], rule, `${what} starts with a rule`);
    assert.notEqual(sections.at(-1), rule, `${what} ends with a rule`);
    sections.forEach((s, i) => assert.ok(!(s === rule && sections[i + 1] === rule), `${what} doubles a rule`));
  };
  for (const [kind, values] of Object.entries(SAMPLES)) {
    check(world.fn.eventDescription_(calendar, kind, values), `${kind}`);
    check(world.fn.eventDescription_(calendar, kind, values, 'Space taken:\nWheels: 4'), `${kind} with space`);
  }
  check(world.fn.compose_('handMade', { ...world.fn.blocks_({ shareUrl: 'webcal://x' }), existing: '' }), 'a hand-made event with no text');
  check(world.fn.compose_('handMade', { ...world.fn.blocks_({ shareUrl: 'webcal://x' }), existing: 'mine' }), 'a hand-made event');
  check(world.fn.compose_('calendar', world.fn.blocks_({ shareUrl: 'webcal://x', sheetUrl: 'https://s' })), 'the calendar');
});

test('an unknown placeholder is an error, not braces on a calendar', () => {
  const world = newWorld();
  world.eval("CONTENT.sources.kiln.source = 'Original note ({dateLabell}): {rowUrl}'");

  assert.throws(
    () => world.fn.eventDescription_(calendarOf(world), 'kiln', SAMPLES.kiln),
    /Unknown placeholder \{dateLabell\}/,
  );
});

test('a typo in wording every event shares fails the run before anything is made', () => {
  const world = newWorld();
  world.eval("CONTENT.share = 'Share: {sharUrl}'");

  assert.throws(() => world.fn.sync(), /Unknown placeholder \{sharUrl\}/);

  assert.equal(world.allEvents().length, 0, 'no event with a broken description was made');
});

test('a typo in one source\'s wording fails only that source, and says why', () => {
  const world = newWorld();
  world.eval("CONTENT.sources.classes.source = 'Row: {rowUrll}'");

  world.fn.sync();

  assert.equal(world.events('Higher Fire · Classes').length, 0, 'no class with a broken description');
  assert.ok(world.events('Higher Fire · Kiln Notes & Events').length > 0, 'the other sources still ran');
  assert.ok(world.logs.some((l) => /Skipping .* creating its events failed \(Unknown placeholder \{rowUrll\}/.test(l.text)));
  assert.match(world.summary(), /failed/);
});

test('a layout naming a block that does not exist is an error', () => {
  const world = newWorld();
  world.eval("CONTENT.layouts.event = ['source', 'sourcee']");
  assert.throws(
    () => world.fn.eventDescription_(calendarOf(world), 'kiln', SAMPLES.kiln),
    /Unknown block "sourcee" in the event layout/,
  );
});

test('the layout decides the order, so moving a block moves it', () => {
  const world = newWorld();
  world.eval("CONTENT.layouts.event = ['share', 'rule', 'source', 'notice']");

  const sections = world.fn.eventDescription_(calendarOf(world), 'kiln', SAMPLES.kiln).split('\n\n');

  assert.match(sections[0], /^Share this calendar:\nwebcal:\/\//);
  assert.equal(sections[1], world.eval('CONTENT.rule'));
  assert.match(sections[2], /^Original note \(Fri, Oct 9\):/);
  assert.match(sections.at(-1), /^Events are generated by AI/);
  assert.ok(!sections.some((s) => /^DISCLAIMER/.test(s)), 'a block left out of the layout is left out');
});

test('a short link is made only for a template that asks for it', () => {
  const world = newWorld();
  const shortened = [];
  world.context.shorten = (url) => {
    shortened.push(url);
    return 'https://s.test/' + shortened.length;
  };
  world.eval('CONTENT.shortenUrl = shorten');

  world.fn.eventDescription_(calendarOf(world), 'kiln', SAMPLES.kiln);
  assert.deepEqual(shortened, [], 'nothing asked for a short link');

  world.eval("CONTENT.sources.kiln.source = 'Row: {rowUrlShort}\\nLong: {rowUrl}'");
  world.eval("CONTENT.share = 'Share: {shareUrlShort}'");
  const text = world.fn.eventDescription_(calendarOf(world), 'kiln', SAMPLES.kiln);

  assert.ok(text.includes('Row: https://s.test/'));
  assert.ok(text.includes('Long: https://sheet.test/row'));
  assert.ok(text.includes('Share: https://s.test/'));
  assert.equal(shortened.length, 2);
  assert.ok(shortened.includes('https://sheet.test/row'));
  assert.ok(shortened.some((url) => url.startsWith('webcal://')));
});

test('with the shortener as it ships, a short-link placeholder shows the full link', () => {
  const world = newWorld();
  world.eval("CONTENT.sources.classes.source = 'Row: {rowUrlShort}'");
  const text = world.fn.eventDescription_(calendarOf(world), 'classes', SAMPLES.classes);
  assert.ok(text.startsWith('Row: https://sheet.test/row'));
});

test('title templates decide where the number and the emoji go', () => {
  const world = newWorld();
  world.eval("CONTENT.titleWithCount = '({count}) {title}'; CONTENT.titleWithEmoji = '{title} {emoji}'");

  world.fn.sync();

  assert.ok(world.events('Higher Fire · Classes').some((e) => e.title === "(18) Just Try It"));
  assert.ok(world.events('Higher Fire · Kiln Notes & Events').some((e) => e.title === 'STUDIO CLOSED FOR THE HOLIDAY 🔴'));
});

test('the space block takes its lines from the config', () => {
  const world = newWorld();
  world.eval("CONTENT.space.heading = 'Room needed:'; CONTENT.space.wheels = '{value} wheels'");
  assert.equal(world.fn.spaceLabel_('10', '').detail, 'Room needed:\n10 wheels');
});

test('the wording lives in content.js and nowhere else in the code', () => {
  const phrases = [
    'Original note',
    'Original row',
    'Original schedule',
    'Space taken',
    'Share this calendar',
    'Class will be glazing',
    'Not an official Higher Fire',
    'Check the original',
    'Check the kiln notes',
    'Community calendar by',
    'Events are generated by AI',
  ];
  const src = path.join(__dirname, '..', 'src');
  for (const file of fs.readdirSync(src).filter((f) => f.endsWith('.js') && f !== 'content.js')) {
    const code = fs.readFileSync(path.join(src, file), 'utf8');
    for (const phrase of phrases) {
      assert.ok(!code.includes(phrase), `${file} says "${phrase}" itself instead of using content.js`);
    }
  }
});

test('content.js still holds every phrase, so the test above is not vacuous', () => {
  const content = fs.readFileSync(path.join(__dirname, '..', 'src', 'content.js'), 'utf8');
  for (const phrase of ['Original note', 'Space taken', 'Share this calendar', 'Not an official Higher Fire', 'Events are generated by AI']) {
    assert.ok(content.includes(phrase), phrase);
  }
});

test('a rule left at the end by an empty last block is dropped, and so is one left at the start', () => {
  const world = newWorld();
  world.eval("CONTENT.layouts.event = ['space', 'rule', 'source', 'rule', 'space']");

  const text = world.fn.eventDescription_(calendarOf(world), 'classes', SAMPLES.classes);

  assert.equal(text, 'Original row (Fri, Oct 9):\nhttps://sheet.test/row');
});
